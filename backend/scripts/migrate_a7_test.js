const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const dotenv = require('dotenv');
const envFile = path.resolve(__dirname, '../.env');
if (!fs.existsSync(envFile)) throw new Error('backend/.env is required to migrate the isolated A7 test database.');
const values = dotenv.parse(fs.readFileSync(envFile));
const url = new URL(values.DATABASE_URL || '');
url.pathname = '/ecogrid_a7_test';
if (url.pathname !== '/ecogrid_a7_test' || !['127.0.0.1', 'localhost', '::1'].includes(url.hostname)) throw new Error('A7 migrations only run against the local ecogrid_a7_test database.');
const child = spawnSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['prisma', 'migrate', 'deploy'], { cwd: path.resolve(__dirname, '..'), env: { ...process.env, ...values, DATABASE_URL: url.toString() }, stdio: 'inherit' });
process.exitCode = child.status || 0;
